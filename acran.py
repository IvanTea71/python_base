# 1. Двойные кавычки внутри строки
string1 = "Он сказал: \"Привет, мир!\""
# 2. Одинарные кавычки внутри строки
string2 = 'Это пример \'одинарных кавычек\' в тексте.'
# 3. Обратный слэш
string3 = "C:\\Users\\Ivan\\Documents\\file.txt"
# 4. Символ новой строки (\n)
string4 = "Первая строка\nВторая строка"
# 5. Символ табуляции (\t)
string5 = "Имя\tВозраст\tГород\nИван\t25\tМосква"
# 6. Многострочная строка
string6 = """Пример многострочной строки:
    "Двойные кавычки"
    'Одинарные кавычки'
    Имя\tВозраст
    Иван\t25
Это последняя строка."""
strings ={"1. Двойные кавычки:":string1,
          "2. Одинарные кавычки:":string2,
          "3. Обратный слэш:":string3,
          "4. Новая строка:":string4,
          "5. Табуляция:":string5,
          "6. Многострочная строка:":string6}
for key, value in strings.items():
    print(key, "-", value)

